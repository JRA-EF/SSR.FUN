// Builds the two publishable copies of docs/project/ROADMAP.html (the source
// you edit; its image paths are relative to that file so it also opens
// straight from the repo):
//
//   node docs/project/roadmap-build.mjs            -> both outputs below
//   node docs/project/roadmap-build.mjs --site     -> public/internal-roadmap.html only
//   node docs/project/roadmap-build.mjs --artifact [outFile]
//
// --site: a full HTML document served at /internal/roadmap (vercel.json
//   rewrite; middleware.ts gates it behind SSR_DASHBOARD_PASSWORD like the
//   other /internal pages). Images point at the site's own /pnl/... and
//   /apple-touch-seal.png, so this copy stays small and IS committed.
// --artifact: the same page with the two brand images inlined as data URIs,
//   for publishing as a self-contained Claude Artifact. Default output
//   docs/project/ROADMAP.built.html is git-ignored (~500 KB of base64).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const src = path.join(here, "ROADMAP.html");

const IMAGES = [
  { rel: "../../public/pnl/eagle-bull.jpg", site: "/pnl/eagle-bull.jpg", mime: "image/jpeg" },
  { rel: "../../public/apple-touch-seal.png", site: "/apple-touch-seal.png", mime: "image/png" },
];

const body = () => {
  let html = fs.readFileSync(src, "utf8").replace(/^<!--[\s\S]*?-->\s*/, "");
  for (const img of IMAGES) if (!html.includes(img.rel)) throw new Error(`ROADMAP.html no longer references ${img.rel}`);
  return html;
};
const swapAll = (html, from, to) => html.split(from).join(to);

function buildSite() {
  let html = body();
  for (const img of IMAGES) html = swapAll(html, img.rel, img.site);
  const doc = `<!doctype html>
<html lang="en">
<head>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<!-- Generated by docs/project/roadmap-build.mjs from docs/project/ROADMAP.html -- edit the source, not this file. -->
${html.replace(/\n<\/style>\n/, "\n</style>\n</head>\n<body>\n")}
</body>
</html>
`;
  const out = path.join(root, "public", "internal-roadmap.html");
  fs.writeFileSync(out, doc, "utf8");
  console.log(`wrote ${path.relative(root, out)} (${(Buffer.byteLength(doc) / 1024).toFixed(0)} KB)`);
}

function buildArtifact(outArg) {
  let html = body();
  for (const img of IMAGES) {
    const dataUri = `data:${img.mime};base64,${fs.readFileSync(path.join(here, img.rel)).toString("base64")}`;
    html = swapAll(html, img.rel, dataUri);
  }
  const out = outArg ?? path.join(here, "ROADMAP.built.html");
  fs.writeFileSync(out, html, "utf8");
  console.log(`wrote ${out} (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB)`);
}

const args = process.argv.slice(2);
if (args[0] === "--site") buildSite();
else if (args[0] === "--artifact") buildArtifact(args[1]);
else { buildSite(); buildArtifact(args[0]); }
